export const textWidth = (s, k = 1) => s.length * 4 * k - k;

export function drawText(img, s, x, y, color, k = 1) {
  s = String(s).toUpperCase();
  for (let n = 0; n < s.length; n++) {
    const g = ROWS[s[n]] || ROWS[' '];
    for (let r = 0; r < 5; r++)
      for (let c = 0; c < 3; c++)
        if (g[r][c] === '#')
          for (let a = 0; a < k; a++) for (let b = 0; b < k; b++) img.set(x + (n * 4 + c) * k + b, y + r * k + a, color);
  }
}
